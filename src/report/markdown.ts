import type { Report } from "../audit/report.js";
import type { Finding } from "../audit/finding.js";

export function formatMarkdown(report: Report): string {
  const { server, counts, summary, scorecard, findings } = report;
  const gradeBadge = getGradeBadgeUrl(scorecard.grade);

  const lines: string[] = [
    `# 🩺 MCP Security & Conformance Audit Report`,
    "",
    `**Server**: \`${server.name ?? "unnamed"}@${server.version ?? "0.0.0"}\`  `,
    `**Protocol**: \`${server.protocolVersion ?? "unknown"}\`  `,
    `**Command**: \`${server.command}\`  `,
    `**Health Grade**: ![Grade](${gradeBadge}) **Score**: \`${scorecard.score}/100\` (${scorecard.status})  `,
    `**Capabilities Discovered**: ${counts.tools} tools, ${counts.resources} resources, ${counts.resourceTemplates} templates, ${counts.prompts} prompts  `,
    "",
    `## Summary`,
    "",
    `| Errors | Warnings | Notes | Total Findings |`,
    `| :---: | :---: | :---: | :---: |`,
    `| ${summary.error === 0 ? "0 ✅" : `${summary.error} ❌`} | ${summary.warn === 0 ? "0" : `${summary.warn} ⚠️`} | ${summary.info} ℹ️ | ${summary.total} |`,
    "",
  ];

  if (findings.length === 0) {
    lines.push(
      "> 🎉 **Clean Conformance**: Zero findings recorded. All protocol and tool safety checks passed.",
      "",
    );
  } else {
    lines.push("## Detailed Findings", "");
    lines.push("| Severity | Rule | Subject | Message | Remediation Hint |");
    lines.push("| :---: | :--- | :--- | :--- | :--- |");

    for (const f of findings) {
      const icon = f.severity === "error" ? "🛑 ERROR" : f.severity === "warn" ? "⚠️ WARN" : "ℹ️ INFO";
      const subject = f.subject ? `\`${f.subject}\`` : `*${f.subjectKind}*`;
      const hint = f.hint ? f.hint.replace(/\|/g, "\\|") : "-";
      const msg = f.message.replace(/\|/g, "\\|");
      lines.push(`| ${icon} | \`${f.ruleId}\` | ${subject} | ${msg} | ${hint} |`);
    }
    lines.push("");
  }

  lines.push("---", `*Generated by [mcp-doctor](https://github.com/bakhtiyor-aminzoda/mcp-linter) v${report.toolVersion}*`);
  return lines.join("\n");
}

function getGradeBadgeUrl(grade: string): string {
  const colors: Record<string, string> = {
    "A+": "brightgreen",
    "A": "green",
    "B": "yellowgreen",
    "C": "yellow",
    "D": "orange",
    "F": "red",
  };
  const color = colors[grade] ?? "lightgrey";
  return `https://img.shields.io/badge/Health_Grade-${encodeURIComponent(grade)}-${color}`;
}
